"""Installing a skill: pick its interpreter, then write `.agent-tools/<skill>`.

The launcher is a short shell script that resolves the project root from its own
location and runs the declared interpreter on the package entry. The interpreter
path is baked in at install time, so the launcher never parses JSON itself; if
the global project moves, reinstall (one command) and the path is rewritten.
"""
from __future__ import annotations
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

from . import config, manifest as manif, paths
from .errors import Exit, fail


def run(project_root: Path, names: list[str]) -> None:
    if not names:
        raise fail(Exit.Install.MISSING_SKILLS, "install: at least one skill name required")
    for name in names:
        package(project_root, name)


def package(project_root: Path, name: str) -> None:
    pkg = paths.package_dir(project_root, name)
    if not pkg.is_dir():
        raise fail(Exit.Install.FAILED, f"install: missing package directory: {pkg}")
    spec = manif.load(pkg)
    kind = manif.kind(spec)
    if kind is None:
        return  # nothing to launch
    if kind != "python":
        raise fail(Exit.Install.FAILED, f"{name}: unsupported install.kind {kind!r}")

    entry = pkg / f"{name}.py"
    if not entry.is_file():
        raise fail(Exit.Install.FAILED, f"{name}: missing entry file: {entry}")

    home = config.global_home(project_root, seed=True)
    interpreter = _provision_runtime(home, name, manif.python_spec(spec))
    _write_launcher(project_root, name, interpreter)

    print(f"install: {name} -> .agent-tools/{name} ({paths.pretty(interpreter)})")


# ------------------------------------------------------------------- launcher


def _write_launcher(project_root: Path, name: str, interpreter: Path) -> None:
    tools = paths.tools_dir(project_root)
    tools.mkdir(parents=True, exist_ok=True)
    target = tools / name
    target.write_text(_stub(name, interpreter), encoding="utf-8")
    target.chmod(0o755)


def _stub(name: str, interpreter: Path) -> str:
    return f"""#!/usr/bin/env bash
# generated by agent-ide install {name}; reinstall to rewrite after a move
set -euo pipefail
_resolve() {{
  local s="${{BASH_SOURCE[0]}}"
  while [ -L "$s" ]; do
    local d
    d="$(cd "$(dirname "$s")" && pwd)"
    s="$(readlink "$s")"
    [[ "$s" != /* ]] && s="$d/$s"
  done
  printf '%s\\n' "$s"
}}
_TOOLS="$(cd "$(dirname "$(_resolve)")" && pwd)"
_ROOT="$(cd "$_TOOLS/.." && pwd)"
_BIN={shlex.quote(str(interpreter))}
_ENTRY="$_ROOT/.agent-ide/skills/{name}/{name}.py"
if [ ! -x "$_BIN" ]; then
  echo "agent-ide: interpreter missing: $_BIN" >&2
  echo "agent-ide: repair: bash $_ROOT/.agent-ide/skills/agent-ide/install.command" >&2
  exit 1
fi
exec "$_BIN" "$_ENTRY" "$@"
"""


# -------------------------------------------------------------------- runtime


def _provision_runtime(global_home: Path, name: str, py: dict) -> Path:
    prefix = paths.runtime_root(global_home) / paths.platform_tag() / py["runtime"]
    interpreter = prefix / "bin" / prefix.name
    wanted = py["requirements"]

    if not interpreter.is_file():
        # `python3.11` has suffix `.11`, so with_suffix would give `python3.gz`.
        archive = prefix.parent / f"{prefix.name}.gz"
        if not archive.is_file():
            if wanted:
                raise fail(
                    Exit.Install.DEP_FAILED,
                    f"{name}: interpreter missing at {interpreter} and {archive.name} is "
                    f"absent, so its requirements cannot be installed",
                )
            # No bundled runtime, nothing to install: the launcher names the
            # interpreter that is running this command. Without this a fresh
            # checkout cannot bootstrap at all, since the archive only exists
            # after the first provisioned install.
            return Path(sys.executable)
        _unpack(archive, prefix)

    _pip(interpreter, wanted)
    return interpreter


def _unpack(archive: Path, prefix: Path) -> None:
    shutil.rmtree(prefix, ignore_errors=True)
    prefix.parent.mkdir(parents=True, exist_ok=True)
    prefix.mkdir(parents=True)
    done = subprocess.run(
        ["tar", "xzf", str(archive), "-C", str(prefix), "--strip-components=1"],
        capture_output=True,
        text=True,
    )
    if done.returncode != 0:
        shutil.rmtree(prefix, ignore_errors=True)
        raise fail(
            Exit.Install.DEP_FAILED,
            f"cannot unpack {archive.name}: {_tail(done) or 'tar failed'}",
        )


def _pip(interpreter: Path, specs: list[str]) -> None:
    """Install what the manifest asks for; pip itself skips satisfied specs."""
    if not specs:
        return
    pip = subprocess.run(
        [str(interpreter), "-m", "pip", "install", *specs],
        capture_output=True,
        text=True,
    )
    if pip.returncode != 0:
        raise fail(Exit.Install.DEP_FAILED, f"pip install {' '.join(specs)} failed: {_tail(pip)}")


def _tail(done: subprocess.CompletedProcess) -> str:
    lines = (done.stderr or done.stdout or "").strip().splitlines()
    return lines[-1] if lines else f"exit {done.returncode}"
